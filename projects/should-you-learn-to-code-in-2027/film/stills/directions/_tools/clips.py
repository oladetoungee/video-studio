# crops of the captured real pages -> _src/clips/*.png + _shared/clips.js (boxes in crop pixels, for highlights)
import json, os
from PIL import Image
D = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
S1 = ('Indeed Hiring Lab · 23 Jul 2026', 'https://hiringlab.indeed.com/2026/07/23/the-labor-market-is-tilting-toward-seniority/')
S2 = ('Indeed Hiring Lab · 8 Jul 2026', 'https://hiringlab.indeed.com/?p=20708')
C = {
 # key, source png, crop box (x0,y0,x1,y1), highlight boxes in source px, source
 'ind-head': ('indeed-seniority.png', (255, 170, 1300, 540), [], S1),
 'ind-45': ('indeed-seniority__4-5-in-software-developm.png', (255, 742, 1300, 822), [(794, 779, 474, 36)], S1),
 'ind-15': ('indeed-ai.png', (300, 591, 1300, 698), [(770, 597, 304, 36)], S2),
 'ind-71': ('indeed-ai.png', (300, 843, 1300, 921), [(331, 848, 919, 36), (331, 884, 322, 36)], S2),
 'ind-45b': ('indeed-seniority__4-5-in-software-developm.png', (788, 777, 1288, 818), [(794, 779, 474, 36)], ('Indeed Hiring Lab, 23 Jul 2026', S1[1])),
 'ind-title': ('indeed-seniority.png', (255, 170, 1300, 360), [], S1),
 'ind-ai-head': ('indeed-ai.png', (255, 170, 1300, 540), [], S2),
}
out = {}
for k, (f, box, hls, (src, url)) in C.items():
    im = Image.open(os.path.join(D, '_src', f)).convert('RGB').crop(box); fn = 'clips/' + k + '.png'; im.save(os.path.join(D, '_src', fn))
    out[k] = {'file': fn, 'w': im.width, 'h': im.height, 'hl': [[x - box[0], y - box[1], w, h] for x, y, w, h in hls], 'source': src, 'date': ('' if k.endswith('b') else 'hiringlab.indeed.com'), 'url': url}
open(os.path.join(D, '_shared/clips.js'), 'w').write('/* generated by _tools/clips.py */\nconst CLIPS = ' + json.dumps(out) + ';\n')
print({k: (v['w'], v['h']) for k, v in out.items()})
