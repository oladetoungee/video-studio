#!/usr/bin/env python3
"""edge cases: real page clippings (crops only, never altered) + highlight boxes (clip px) -> film/assets/src/clip-*.png + clips.js (CLIPS).
The B-look clips (bbc, wired, azure) come from film/stills/directions/_shared/clips.js; new captures (stripe, sakurity, hyrum) in assets/src/cap/ (full pages, never overwritten)."""
import json, os, re
from PIL import Image
D = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); S = os.path.join(D, 'assets/src')
old = json.loads(re.search(r'const CLIPS = (\{.*\});', open(os.path.join(D, 'stills/directions/_shared/clips.js')).read()).group(1))
NEW = {
 'stripe': ('stripe.png', (440, 130, 1130, 490), [[325, 103, 340, 26], [21, 323, 163, 26]], 'Stripe API docs, Idempotent requests', '', 'https://docs.stripe.com/api/idempotent_requests'),
 'sakurity': ('sakurity.png', (440, 144, 1480, 392), [[88, 218, 451, 27]], 'Egor Homakov, Sakurity', '21 May 2015', 'https://sakurity.com/blog/2015/05/21/starbucks.html'),
 'sakurity-race': ('sakurity.png', (430, 1900, 1480, 1985), [[565, 2, 210, 34]], 'Egor Homakov, Sakurity', '21 May 2015', 'https://sakurity.com/blog/2015/05/21/starbucks.html'),
 'hyrum': ('hyrum.png', (0, 24, 640, 336), [[64, 205, 344, 26], [64, 280, 318, 26]], 'hyrumslaw.com, Hyrum Wright', '', 'https://www.hyrumslaw.com/'),
}
out = dict(old)
for k, (f, box, hl, src, date, url) in NEW.items():
    Image.open(os.path.join(S, 'cap', f)).convert('RGB').crop(box).save(os.path.join(S, k + '.png'))
    out[k] = {'w': box[2] - box[0], 'h': box[3] - box[1], 'hl': hl, 'source': src, 'date': date, 'url': url}
open(os.path.join(S, 'clips.js'), 'w').write('/* generated by film/tools/clips.py: real page clippings (crops only) + highlight boxes in clip px */\nconst CLIPS = ' + json.dumps(out) + ';\n')
print({k: (v['w'], v['h']) for k, v in out.items()})
