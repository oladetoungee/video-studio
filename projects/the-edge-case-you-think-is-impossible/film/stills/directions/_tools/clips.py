# Crop the real page captures into clippings (crops only, nothing altered) + highlight boxes (clip px, set by eye on the capture).
# Writes _shared/clips.js
import json, os
from PIL import Image
D = os.path.abspath(os.path.join(os.path.dirname(__file__), '..')); S = os.path.join(D, '_src'); O = os.path.join(S, 'clips'); os.makedirs(O, exist_ok=True)
URL = {'bbc': 'https://www.bbc.com/future/article/20160325-the-names-that-break-computer-systems',
       'wired': 'https://www.wired.com/story/null-license-plate-landed-one-hacker-ticket-hell/',
       'azure': 'https://azure.microsoft.com/en-us/blog/summary-of-windows-azure-service-disruption-on-feb-29th-2012/'}
def clip(name, img, box, hl, source, date, site):
    im = Image.open(os.path.join(S, img)).convert('RGB'); im.crop(box).save(os.path.join(O, name + '.png'))
    return name, {'w': box[2] - box[0], 'h': box[3] - box[1], 'hl': hl, 'source': source, 'date': date, 'url': URL[site]}
out = dict([
  clip('bbc-head', 'bbc.png', (400, 170, 1520, 460), [], 'BBC Future, Chris Baraniuk', '25 Mar 2016', 'bbc'),
  clip('bbc-jn', 'bbc__jennifer-null.png', (400, 960, 1360, 1160), [[14, 74, 575, 34], [458, 112, 441, 34]], 'BBC Future, Chris Baraniuk', '25 Mar 2016', 'bbc'),
  clip('wired-head', 'wired.png', (80, 90, 1700, 340), [[0, 0, 0, 0]], 'WIRED, Brian Barrett', '13 Aug 2019', 'wired'),
  clip('wired-plate', 'wired.png', (96, 390, 1232, 1146), [], 'WIRED (photo Elena Lacey / Getty Images)', '13 Aug 2019', 'wired'),
  clip('azure', 'azure__adding-one-to-its-year.png', (420, 470, 1500, 860), [[682, 224, 284, 34], [222, 316, 240, 34]], 'Microsoft Azure blog', '9 Mar 2012', 'azure'),
])
out['wired-head']['hl'] = []
json.dump(out, open(os.path.join(O, 'clips.json'), 'w'), indent=1)
open(os.path.join(D, '_shared', 'clips.js'), 'w').write('/* generated by _tools/clips.py: real page clippings (crops only) + highlight boxes in clip px */\nconst CLIPS = ' + json.dumps(out) + ';\n')
for k, v in out.items(): print(k, v['w'], v['h'], v['hl'])
