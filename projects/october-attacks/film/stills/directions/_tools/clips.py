# Crop real article captures into clean clippings (article column only; nothing altered) + highlight boxes in clip px.
import json, os
from PIL import Image
S = os.path.join(os.path.dirname(__file__), '..', '_src'); O = os.path.join(S, 'clips')
def clip(name, src, box, phrase=None, jsonf=None, source='', date=''):
    im = Image.open(os.path.join(S, src)).convert('RGB'); x0, y0, x1, y1 = box
    c = im.crop(box); c.save(os.path.join(O, name + '.png'))
    hl = []
    if phrase and phrase.startswith('main:'):
        j = json.load(open(os.path.join(S, jsonf)))
        for ph in phrase[5:].split('|'):
            for r in j['found'][ph]:
                hl.append([round(r[0] * 1.5 - x0), round((r[1] - j['clipTop']) * 1.5 - y0), round(r[2] * 1.5), round(r[3] * 1.5)])
        phrase = None
    if phrase:
        j = json.load(open(os.path.join(S, jsonf)))
        for r in j['focus'][phrase]['rects']:
            hl.append([round(r[0] * 1.5 - x0), round(r[1] * 1.5 - y0), round(r[2] * 1.5), round(r[3] * 1.5)])
    return name, {'file': 'clips/' + name + '.png', 'w': x1 - x0, 'h': y1 - y0, 'hl': hl, 'source': source, 'date': date, 'url': json.load(open(os.path.join(S, (jsonf or src.split('__')[0].replace('.png', '') + '.json'))))['url']}
out = dict([
  clip('php-quote', 'bc-php__before-any-application-c.png', (60, 605, 1350, 822), 'before any application code runs', 'bc-php.json', 'BleepingComputer', 'Oct 21, 2026'),
  clip('php-head', 'bc-php.png', (60, 160, 1350, 258), None, 'bc-php.json', 'BleepingComputer', 'Oct 21, 2026'),
  clip('zeabur-quote', 'bc-zeabur__the-admin-tokens-had-no-.png', (60, 620, 1350, 858), 'The admin tokens had no expiry', 'bc-zeabur.json', 'BleepingComputer', 'Oct 20, 2026'),
  clip('zeabur-head', 'bc-zeabur.png', (60, 160, 1350, 258), None, 'bc-zeabur.json', 'BleepingComputer', 'Oct 20, 2026'),
  clip('emudhra-quote', 'bc-emudhra__so-weak-that-anyone-coul.png', (60, 728, 1350, 960), 'so weak that anyone could recover them almost instantly', 'bc-emudhra.json', 'BleepingComputer', 'Oct 2026, found Oct 17'),
  clip('railway-text', 'tc-railway__may-have-accessed-encryp.png', (190, 600, 1250, 860), 'may have accessed encrypted environment variables', 'tc-railway.json', 'TechCrunch', 'Oct 22, 2026'),
  clip('railway-revoke', 'tc-railway__should-revoke-and-rotate.png', (190, 690, 1250, 870), 'should revoke and rotate all of their keys', 'tc-railway.json', 'TechCrunch', 'Oct 22, 2026'),
  clip('railway-head', 'tc-railway.png', (0, 40, 1880, 680), 'main:revoke|secret keys', 'tc-railway.json', 'TechCrunch', 'Oct 22, 2026'),
])
json.dump(out, open(os.path.join(O, 'clips.json'), 'w'), indent=1)
open(os.path.join(S, '..', '_shared', 'clips.js'), 'w').write('/* generated by _tools/clips.py: real article clippings (crops only) + highlight boxes in clip px */\nconst CLIPS = ' + json.dumps(out) + ';\n'); print(json.dumps(out, indent=0)[:1500])
