#!/usr/bin/env python3
"""Merge the real article clippings (direction-stage crops in stills/directions/_src/clips + new captures in data/clips.json)
into assets/src/, write scenes/clips.js (const CLIPS) and film.json "images" (clip_<name>). Crops only, never altered."""
import json, os, shutil
R = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
old = json.load(open(os.path.join(R, 'stills/directions/_src/clips/clips.json')))
new = json.load(open(os.path.join(R, 'data/clips.json')))
out = {}
for k, v in old.items():
    src = os.path.join(R, 'stills/directions/_src', v['file']); dst = os.path.join(R, 'assets/src', k + '.png')
    if not os.path.exists(dst): shutil.copy(src, dst)
    out[k] = {**v, 'file': 'assets/src/' + k + '.png'}
for k, v in new.items():
    out[k] = {kk: v[kk] for kk in ('file', 'w', 'h', 'hl', 'source', 'date', 'url')}
over = os.path.join(R, 'data/clips_hl.json')   # hand-set highlight boxes (clip px) where the phrase crossed links
if os.path.exists(over):
    for k, hl in json.load(open(over)).items(): out[k]['hl'] = hl
open(os.path.join(R, 'scenes/clips.js'), 'w').write('/* generated by tools/clipsjs.py: real article clippings (crops only) + highlight boxes in clip px */\nconst CLIPS = ' + json.dumps(out) + ';\n')
fj = os.path.join(R, 'film.json'); man = json.load(open(fj))
man['images'] = {**{k: v for k, v in man.get('images', {}).items() if not k.startswith('clip_')}, **{'clip_' + k: v['file'] for k, v in out.items()}}
json.dump(man, open(fj, 'w'), indent=2, ensure_ascii=False)
print(len(out), 'clips:', ', '.join(out))
