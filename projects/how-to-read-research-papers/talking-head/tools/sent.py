#!/usr/bin/env python3
"""RP_SENT (her sentences after the cleanup cuts, keys s0..sN by sentence index on the raw timeline) -> moments/sent.js.
The plan (moments/plan.js) refers to sentences by these keys; RP_RAW = each sentence's raw start (a guard against a phrase
matching in the wrong place)."""
import json, os, re
HERE = os.path.dirname(os.path.abspath(__file__)); TH = os.path.dirname(HERE)
man = json.load(open(os.path.join(TH, 'talking-head.json'))); full = [m for m in man['moments'] if m['id'] == 'full'][0]
cuts = full['cuts']; w = json.load(open(os.path.join(TH, 'data/raw_words.json')))
keep = [x for x in w if full['in'] <= x['t'] < (full['out'] if isinstance(full['out'], (int, float)) else 1e9) and not any(a <= x['t'] < b for a, b in cuts)]
sent = []; cur = []
for x in w:
    cur.append(x)
    if re.search(r'[.?!]$', x['w']): sent.append(cur); cur = []
if cur: sent.append(cur)
ks = set(id(x) for x in keep); out = {}; raw = {}
n = lambda s: re.sub(r"[^a-z0-9']", '', s.lower().replace('’', "'"))
for i, s in enumerate(sent):
    ws = [x for x in s if id(x) in ks]
    if not ws: continue
    out['s%d' % i] = ' '.join(n(x['w']) for x in ws if n(x['w'])); raw['s%d' % i] = round(ws[0]['t'], 2)
open(os.path.join(TH, 'moments/sent.js'), 'w').write('/* generated by talking-head/tools/sent.py: her sentences after the cleanup cuts (keys = sentence index on the raw timeline) */\n\'use strict\';\nconst RP_SENT = ' + json.dumps(out, indent=0) + ';\nconst RP_RAW = ' + json.dumps(raw) + ';\n')
print(len(out), 'sentences')
