#!/usr/bin/env python3
"""Real page clippings (crops only, never altered) + highlight boxes (clip px) -> film/assets/src/*.png + clips.js (CLIPS).
Sources: film/stills/directions/_src (captured 2026-11-02, see film/assets/CREDITS.md). --debug writes boxes drawn on each crop."""
import json, os, sys, shutil
from PIL import Image, ImageDraw
HERE = os.path.dirname(os.path.abspath(__file__)); P = os.path.dirname(os.path.dirname(HERE))
SRC = os.path.join(P, 'film/stills/directions/_src'); OUT = os.path.join(P, 'film/assets/src'); os.makedirs(OUT, exist_ok=True)
CL = {
 # key: (file, crop box in file px, [highlight boxes in FILE px], source, date, url)
 'caine-title': ('caine.png', (640, 172, 1390, 292), [[652, 254, 112, 34]], 'open.clemson.edu  ·  Kelly Caine, CHI 2016', '', 'https://open.clemson.edu/computing_pubs/28'),
 'caine-abs': ('caine__most-common-sample-size.png', (646, 752, 1372, 834), [[872, 756, 112, 24], [1244, 782, 92, 24], [652, 808, 262, 24]],
               'Kelly Caine, “Local Standards for Sample Size at CHI”, CHI 2016', '', 'https://open.clemson.edu/computing_pubs/28'),
 'pubmed-title': ('pubmed__industry-sponsorship.png', (220, 770, 1160, 890), [[222, 772, 890, 52]], 'PubMed 28207928  ·  Lundh et al., Cochrane Review 2017', '', 'https://pubmed.ncbi.nlm.nih.gov/28207928/'),
 'pubmed-conc': ('pubmed__leads-to-more-favorable-.png', (220, 738, 1290, 812), [[484, 745, 800, 28], [222, 778, 612, 28]],
                 'Lundh et al., “Industry sponsorship and research outcome”, Cochrane 2017 (PubMed)', '', 'https://pubmed.ncbi.nlm.nih.gov/28207928/'),
 'zotero': ('zotero__free.png', (520, 520, 1400, 640), [[786, 538, 58, 40], [815, 590, 150, 42]], 'zotero.org', '', 'https://www.zotero.org/'),
 'zotero-hero': ('zotero__free.png', (0, 0, 1920, 640), [], 'zotero.org', '', 'https://www.zotero.org/'),
}
debug = '--debug' in sys.argv; meta = {}
for k, (f, box, hls, src, date, url) in CL.items():
    im = Image.open(os.path.join(SRC, f)).convert('RGB').crop(box); im.save(os.path.join(OUT, k + '.png'))
    hl = [[b[0] - box[0], b[1] - box[1], b[2], b[3]] for b in hls]
    meta[k] = {'w': im.width, 'h': im.height, 'hl': hl, 'source': src, 'date': date, 'url': url}
    if debug:
        d = im.copy(); dr = ImageDraw.Draw(d)
        for b in hl: dr.rectangle([b[0], b[1], b[0] + b[2], b[1] + b[3]], outline=(255, 0, 0), width=2)
        d.save(os.path.join(sys.argv[sys.argv.index('--debug') + 1], 'dbg-' + k + '.png'))
# Keshav's paper: the two pages (200 dpi renders of the free PDF) + phrase boxes (pt: [x0, baseline, x1])
for p in ('keshav_p1.png', 'keshav_p2.png'): shutil.copy(os.path.join(SRC, p), os.path.join(OUT, p))
for f in os.listdir(os.path.join(SRC, 'pexels')): shutil.copy(os.path.join(SRC, 'pexels', f), os.path.join(OUT, 'px-' + f))
phr = json.load(open(os.path.join(SRC, 'keshav_phr.json'))); phr.update(json.load(open(os.path.join(HERE, 'keshav_extra.json'))))
open(os.path.join(OUT, 'clips.js'), 'w').write('/* generated by talking-head/tools/clips.py: real page clippings (crops only) + highlight boxes in clip px;\n * KESHAV = phrase boxes on the two pages of S. Keshav, "How to Read a Paper" (2007), in pt: [x0, baseline, x1] */\nconst CLIPS = ' + json.dumps(meta) + ';\nconst KESHAV = ' + json.dumps(phr) + ';\n')
print('ok', len(meta), 'clips')
