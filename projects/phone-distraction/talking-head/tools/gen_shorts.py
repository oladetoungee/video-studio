#!/usr/bin/env python3
"""Writes shorts/sNN.js for every "kind": "short" moment (9:16, SHORTS-PLAYBOOK): her on camera on the first line (the hook),
then the film's own screens (synced by her words) alternating with her: L9 cutaway (full page) and L5 half and half (film on
top), keywords (L8) on the film's marked words. Aim: 35-60 % of the short on film inserts."""
import json, os, re, importlib.util
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
spec = importlib.util.spec_from_file_location('gf', os.path.join(ROOT, 'tools/gen_full.py'))
src = open(os.path.join(ROOT, 'tools/gen_full.py')).read().replace('\nmain()\n', '\n')
G = {'__file__': os.path.join(ROOT, 'tools/gen_full.py')}; exec(compile(src, 'gen_full', 'exec'), G)
norm, marked, js = G['norm'], G['marked'], G['js']
RAW = json.load(open(os.path.join(ROOT, 'data/raw_words.json')))
EDL = json.load(open(os.path.join(ROOT, 'data/edl.json')))
HOOK = {'s01': ['Instagram is free.', 'You’re *not paying.*'], 's02': ['Nothing’s there.', 'You *check anyway.*'],
  's03': ['Its inventor says', 'it’s *addictive.*'], 's04': ['Books end.', 'Your feed *doesn’t.*'],
  's05': ['Notification badges', 'were reportedly *blue.*'], 's06': ['The EU vs', '*infinite scroll*'], 's07': ['I quit Instagram', 'for *six years.*'],
  's08': ['Designed', 'to *distract you.*'], 's09': ['Apps that', '*change behaviour*'], 's10': ['Motivation. Ability.', '*Prompt.*'],
  's11': ['The next video', 'plays *on its own.*'], 's12': ['Checking your likes?', '*Intentional design.*'], 's13': ['Notifications on', 'for *one week*'],
  's14': ['Make your phone', '*less rewarding*'], 's15': ['What do I need', 'from *Instagram?*'], 's16': ['Your attention', 'is an *asset.*']}
import sys
ONLY = set(sys.argv[1:])   # ids to (re)write; none = every short
MAN = json.load(open(os.path.join(ROOT, 'talking-head.json')))
for m in MAN['moments']:
    if m['kind'] != 'short' or (ONLY and m['id'] not in ONLY): continue
    clips = EDL[m['id']]['clips']; ws = []
    for ci, (a, b) in enumerate(clips):
        for w in RAW:
            if w['t'] >= a - 0.08 and w['t'] < b - 0.03: ws.append(dict(w, k=ci))
    # breath phrases of 2.5-5 s
    C, cur = [], []
    for i, w in enumerate(ws):
        cur.append(w); d = w['e'] - cur[0]['t']; end_s = w['w'][-1] in '.?!'; cl = w['w'][-1] in ',;:'
        if i == len(ws) - 1 or (end_s and d >= 2.2) or (cl and d >= 3.2) or d >= 5.0: C.append(cur); cur = []
    if cur: C.append(cur)
    lines, keys, film_s, tot = [], {}, 0.0, 0.0; last = None; fi = 0
    for n, c in enumerate(C):
        ph = ' '.join(norm(w['w']) for w in c if norm(w['w'])); k = f'p{n}'; keys[k] = ph; d = c[-1]['e'] - c[0]['t']; tot += d
        mk = marked(c)
        if n == 0: lay = 'talk'   # no big overlay text at the start of a short (her note 2026-10-18: the label is the only top text)
        elif film_s / max(1, tot) < 0.48 and last not in ('cutaway', 'half'): lay = 'cutaway' if fi % 2 == 0 else 'half'; fi += 1
        elif mk and last != 'keyword': lay = 'keyword'
        else: lay = 'talk' if last != 'talk' else ('half' if last != 'half' else 'cutaway')
        if lay in ('cutaway', 'half'): film_s += d
        if lay == 'shout': lines.append(f"  TH.shout(k.{k}, {js(HOOK.get(m['id'], [m['label']]))});   // L3 the hook a stranger reads in the first second")
        elif lay == 'talk': lines.append(f"  TH.talk(k.{k}, {{ frame: '{['close', 'mid', 'tight'][n % 3]}', alt: {str(n % 2 == 1).lower()} }});")
        elif lay == 'keyword': lines.append(f"  TH.keyword(k.{k}, {js('~' + mk + '~')});")
        else: lines.append(f"  TH.{lay}(k.{k}, {{ film: {{}}{', side: \'bottom\'' if lay == 'half' else ''} }});")
        last = lay
    # L12: the payoff word in her caption, near the end
    for c in reversed(C[-3:]):
        mk = marked(c)
        if mk:
            w0 = mk.split()[0]; kk = 'p' + str(C.index(c)); lines.append(f"  TH.highlight(WT(k.{kk}, {js(w0)}), {js(w0.lower())});   // L12"); break
    out = [f"/* {m['id']} · {m['label']}{(' / ' + m['sublabel']) if m.get('sublabel') else ''}: generated by tools/gen_shorts.py. Her hook on camera, then film inserts",
           " * (the motion film, synced by her words) alternating with her, keywords on the film's marked words. 9:16, her caption spec. */",
           "'use strict';", "function WT(ph, word) { const n = (s) => s.toLowerCase().replace(/[’]/g, \"'\").replace(/[^a-z0-9']/g, ''); const ws = WORDS.slice(ph.i, ph.i + ph.w.length); const k = ws.findIndex(x => x.n === n(word)); return ph.w[k < 0 ? 0 : k]; }", "function buildMoment() {", "  const k = PS({"] + [f"    {k}: {js(v)}," for k, v in keys.items()] + ["  });"] + lines + ["}"]
    os.makedirs(os.path.join(ROOT, 'shorts'), exist_ok=True)
    open(os.path.join(ROOT, m['script']), 'w').write('\n'.join(out) + '\n')
    print(m['id'], len(C), 'phrases, film', round(100 * film_s / tot), '%')
