#!/usr/bin/env python3
"""Measured fixes the film applies after its scenes are built (scenes/nudges.js, read by film.js and kit.js):
  CUE_NUDGE  role@time -> seconds: each sound cue moved onto the frame where the picture changes (lab audit, clear hits only;
             with RETIME=1 also sound QA's first peak vs the visual frame)
  CUE_DROP   cues that sat under the bed (sound QA over_bed < 3 dB): fewer, louder sounds
  HOLDS      [t0, t1] dead holds from the lab audit: kit.js adds a 5 % push-in at the middle of each
Keys are the cue's ORIGINAL time. Run: lab.mjs audit + soundqa.py -> this -> render.mjs meta -> stems.py -> check again."""
import json, os, re
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
path = os.path.join(ROOT, 'scenes/nudges.js')
txt = open(path).read() if os.path.exists(path) else ''
def table(name, default):
    m = re.search(r'const ' + name + r' = (.*?);\n', txt, re.S); return json.loads(m.group(1)) if m else default
NUD, DROP, HOLDS = table('CUE_NUDGE', {}), table('CUE_DROP', []), table('HOLDS', [])
def orig_key(name, t):
    for k, v in NUD.items():
        kn, kt = k.split('@')
        if kn == name and abs(float(kt) + v - t) < 0.006: return k
    return f'{name}@{t:.2f}'
d = json.load(open(os.path.join(ROOT, 'build/qa/audit_16x9.json')))
n = 0
for c in d['checks']:
    if c.get('kind') != 'sound sync' or c.get('pass') or not c.get('clear') or c.get('soft') or c.get('onCut'): continue
    name, t = re.match(r'(\w+) @ ([\d.]+) s', c['label']).groups(); k = orig_key(name, float(t))
    NUD[k] = round(NUD.get(k, 0) + (c['got'] - c['want']) / 30, 3); n += 1
print(n, 'cues nudged (audit)')
sq = os.path.join(ROOT, 'build/qa/soundqa.json')
if os.path.exists(sq) and os.environ.get('DROP', '1') == '1':
    S = json.load(open(sq)); nd = nq = 0
    for c in S['cues']:
        k = orig_key(c['name'], c['t'])
        if c.get('over_bed_db') is not None and c['over_bed_db'] < float(os.environ.get('DROP_DB', '3')) and c['name'] not in ('burst', 'pull', 'refresh', 'type'):
            if k not in DROP: DROP.append(k); nd += 1
            continue
        off = c.get('first_vs_target_ms')
        if os.environ.get('RETIME') == '1' and off is not None and (off > 66 or off < -33): NUD[k] = round(NUD.get(k, 0) - off / 1000, 3); nq += 1
    print(nd, 'quiet cues dropped,', nq, 'retimed from sound QA')
# THIN=1: the same sound role again within 0.8 s (pop rings, receipt rows printing in a burst): every other one dropped
if os.environ.get('THIN', '1') == '1':
    mp = os.path.join(ROOT, 'data/meta.json'); nt = 0
    if os.path.exists(mp):
        C = sorted(json.load(open(mp))['CUES'], key=lambda c: c['t']); last = {}
        for c in C:
            k = orig_key(c['name'], c['t'])
            if k in DROP: continue
            p = last.get(c['name'])
            if p is not None and c['t'] - p < 0.8 and c['name'] not in ('burst', 'pull', 'type'):
                DROP.append(k); nt += 1; last[c['name']] = -1e9; continue
            last[c['name']] = c['t']
    print(nt, 'cues thinned (same role within 0.8 s)')
# HOLDS=0: leave the dead-hold push-ins as they are (no picture change while the visuals are under review)
for x in (d['motion'] if os.environ.get('HOLDS', '1') == '1' else []):
    if x['kind'] == 'dead hold':
        h = [round(x['frame'] / 30, 2), round(x['frame'] / 30 + float(x['detail'].split(' s')[0]), 2)]
        if all(abs(h[0] - p[0]) > 0.5 for p in HOLDS): HOLDS.append(h)
open(path, 'w').write("/* generated by tools/nudges.py (lab audit + sound QA); see the tool's header */\n'use strict';\nconst CUE_NUDGE = " + json.dumps(NUD) + ";\nconst CUE_DROP = " + json.dumps(sorted(set(DROP))) + ";\nconst HOLDS = " + json.dumps(HOLDS) + ";\n")
print(len(NUD), 'nudges,', len(set(DROP)), 'drops,', len(HOLDS), 'push-ins')
