#!/usr/bin/env python3
"""scholarships film: real official page crops (data/clips.json from tools/capture.mjs + hand-cut crops below) and the
Pexels photos -> scenes/clips.js (const CLIPS, PHOTOS) and film.json "images" (clip_<name>, photo_<name>). Crops only."""
import json, os
R = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
clips = json.load(open(os.path.join(R, 'data/clips.json')))
clips['si-dates'] = {'file': 'assets/src/si-dates.png', 'w': 990, 'h': 222, 'hl': [[40, 12, 340, 34], [40, 153, 190, 34]], 'source': 'si.se', 'date': 'checked 2 Nov 2026',
                     'url': 'https://si.se/en/apply/scholarships/swedish-institute-scholarships-for-global-professionals/'}
out = {k: {kk: v[kk] for kk in ('file', 'w', 'h', 'hl', 'source', 'date', 'url')} for k, v in clips.items()}
photos = {
  'stockholm': ['Jakob Stöberl', 'Sweden'], 'budapest': ['Efrem Efre', 'Hungary'], 'tallinn': ['Sergei Gussev', 'Estonia'],
  'amsterdam': ['Magda Ehlers', 'Netherlands'], 'berlin': ['Nino Keller', 'Germany'], 'london': ['Gianluca Pugliese', 'United Kingdom'],
  'brussels': ['Atypeek Dgn', 'European Union'], 'gradcap': ['Towfiqu barbhuiya', ''],
}
ph = {k: {'file': 'assets/photos/' + k + '.jpg', 'by': v[0], 'place': v[1]} for k, v in photos.items()}
open(os.path.join(R, 'scenes/clips.js'), 'w').write('/* generated by tools/clipsjs.py: official page crops (highlight boxes in crop px) + Pexels photos */\nconst CLIPS = ' + json.dumps(out) + ';\nconst PHOTOS = ' + json.dumps(ph, ensure_ascii=False) + ';\n')
fj = os.path.join(R, 'film.json'); man = json.load(open(fj))
man['images'] = {**{'clip_' + k: v['file'] for k, v in out.items()}, **{'photo_' + k: v['file'] for k, v in ph.items()}}
json.dump(man, open(fj, 'w'), indent=2, ensure_ascii=False)
print(len(out), 'clips,', len(ph), 'photos')
