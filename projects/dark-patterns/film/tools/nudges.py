#!/usr/bin/env python3
"""Read the lab audit's sound-sync fails (build/qa/audit_16x9.json) and write scenes/nudges.js: {'role@t': seconds},
merged with the existing ones. kit.js shifts each cue by its nudge. Run: node studio/tools/lab.mjs audit dark-patterns; python3 film/tools/nudges.py"""
import json, os, re
R = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
a = json.load(open(os.path.join(R, 'build/qa/audit_16x9.json'))); p = os.path.join(R, 'scenes/nudges.js')
old = {}
if os.path.exists(p): old = json.loads(open(p).read().split('=', 1)[1].strip().rstrip(';'))
n = 0
for c in a['checks']:
    if c.get('kind') != 'sound sync' or c.get('pass') or not c.get('clear'): continue
    m = re.match(r'(\S+) @ ([\d.]+) s', c['label']); k = f"{m.group(1)}@{float(m.group(2)):.2f}"
    old[k] = round(old.get(k, 0) + (c['got'] - c['want']) / 30, 3); n += 1
open(p, 'w').write('/* generated by tools/nudges.py from the lab audit: sound cue -> seconds to move it onto its picture change */\nconst NUDGE = ' + json.dumps(old) + ';\n')
print(n, 'nudges')
